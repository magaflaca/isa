"""Writes a move plan for the members declared inside #regions of a class.

    python scripts/region_plan.py <file.cs> <Ns.SourceClass> "<Region>=<Ns.Target>" ... > plan.move
"""
import re
import sys

path, source = sys.argv[1], sys.argv[2]
targets = dict(arg.split("=", 1) for arg in sys.argv[3:])
text = open(path, encoding="utf-8-sig").read().replace("\r\n", "\n")
region = None
names = {}
declaration = re.compile(r"^\t(?:\[[^\]]*\]\s*)?(?:public|private|internal|protected)(?: (?:static|readonly|const|async|unsafe|volatile|override|new))* (?:(?:class|struct|enum|record|interface) (\w+)|[\w<>\[\],.?() ]+? (\w+)\s*(?:\(|=|;|\{|$))")
for line in text.split("\n"):
    m = re.match(r"^\t#region (.+)$", line)
    if m:
        region = m.group(1).strip()
        continue
    if line.startswith("\t#endregion"):
        region = None
        continue
    if region not in targets:
        continue
    d = declaration.match(line)
    if d:
        name = d.group(1) or d.group(2)
        if name and name not in names:
            names[name] = targets[region]
print(f"# generated by region_plan.py from {path}")
for name, target in names.items():
    print(f"{source}.{name} -> {target}")

"""Writes MODULES.md: every IsaClient class, grouped by namespace, with the first sentence of its <summary>.

    python tools/refactor/scripts/module_index.py           (writes IsaClient/MODULES.md)
    python tools/refactor/scripts/module_index.py --missing (lists classes without a summary)
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
SRC = os.path.join(ROOT, "src")
DECL = re.compile(r"((?:^///[^\n]*\n)*)^(?:\[[^\n]*\]\n)?(?:public|internal) (?:static |sealed |abstract )*(class|struct|enum) (\w+)", re.M)


def summary(doc):
    text = " ".join(line.strip()[3:].strip() for line in doc.strip().splitlines())
    m = re.search(r"<summary>(.*?)</summary>", text)
    if not m:
        return None
    text = re.sub(r"<see cref=\"(?:[\w.]*\.)?(\w+)\"\s*/>", r"\1", m.group(1))
    text = re.sub(r"<c>(.*?)</c>", r"`\1`", text)
    text = re.sub(r"<[^>]+>", "", text).strip()
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return first


entries = {}
missing = []
for path in sorted(glob.glob(os.path.join(SRC, "IsaClient.*", "*.cs"))):
    namespace = os.path.basename(os.path.dirname(path))
    text = open(path, encoding="utf-8-sig").read().replace("\r\n", "\n")
    for m in DECL.finditer(text):
        name = m.group(3)
        line = summary(m.group(1)) if m.group(1) else None
        if line is None:
            missing.append(f"{namespace}/{os.path.basename(path)}: {name}")
        entries.setdefault(namespace, []).append((name, os.path.basename(path), line or ""))

if "--missing" in sys.argv:
    print("\n".join(missing))
    print(f"{len(missing)} without summary")
    sys.exit(0)

out = ["# IsaClient modules", "", "Generated by `python tools/refactor/scripts/module_index.py`: every class under `src/IsaClient.*` and the",
       "first sentence of its `<summary>`. Regenerate it after adding or moving classes. Architecture rules: ARCHITECTURE.md.", ""]
for namespace in sorted(entries):
    out.append(f"## {namespace}")
    out.append("")
    out.append("| Class | File | What it does |")
    out.append("|---|---|---|")
    for name, file, line in entries[namespace]:
        out.append(f"| `{name}` | {file} | {line.replace('|', '/')} |")
    out.append("")
open(os.path.join(ROOT, "MODULES.md"), "w", encoding="utf-8").write("\n".join(out))
print(f"MODULES.md: {sum(len(v) for v in entries.values())} classes, {len(missing)} without summary")
